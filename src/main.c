//==================================================
// main.c
//==================================================

#include "freertos/FreeRTOS.h"
#include "freertos/task.h"

#include "wifi_manager.h"
#include "audio.h"
#include "fsm.h"
#include "motor.h"
#include "oled.h"
#include "touch.h"

void app_main()
{
    //==============================================
    // WIFI
    //==============================================

    wifi_init();

    //==============================================
    // AUDIO
    //==============================================

    audio_init();

    //==============================================
    // MOTOR
    //==============================================

    motor_init();

    //==============================================
    // OLED
    //==============================================

    oled_init();

    //==============================================
    // TOUCH
    //==============================================

    touch_init();

    //==============================================
    // FSM
    //==============================================

    fsm_init();

    //==============================================
    // MAIN LOOP
    //==============================================

    while(true)
    {
        fsm_update();

        motor_update();

        vTaskDelay(
            pdMS_TO_TICKS(10)
        );
    }
}